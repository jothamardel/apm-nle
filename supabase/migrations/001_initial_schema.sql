create or replace function public.get_public_analytics_summary()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'total_members', count(*),
    'pvc_holders', count(*) filter (where pvc_status = 'has_pvc'),
    'planning_pvc', count(*) filter (where pvc_status = 'planning_pvc'),
    'non_pvc_supporters', count(*) filter (where pvc_status = 'no_pvc_supporter'),
    'diaspora_supporters', count(*) filter (where pvc_status = 'diaspora'),
    'protect_ballots_count', count(*) filter (where 'protect_ballots' = any(action_teams)),
    'social_media_count', count(*) filter (where 'social_media' = any(action_teams)),
    'grassroots_mobilization_count', count(*) filter (where 'grassroots_mobilization' = any(action_teams)),
    'fundraising_outreach_count', count(*) filter (where 'fundraising_outreach' = any(action_teams)),
    'states_covered', count(distinct state_id),
    'lgas_covered', count(distinct lga_id),
    'wards_covered', count(distinct ward_id),
    'polling_units_covered', count(distinct polling_unit_id)
  )
  from public.profiles;
$$;

create or replace function public.get_state_breakdown()
returns table (
  state_id smallint,
  state_name text,
  state_code text,
  geopolitical_zone text,
  total_members bigint,
  pvc_holders bigint,
  non_pvc_supporters bigint,
  protect_ballots bigint,
  social_media bigint,
  lgas_covered bigint,
  wards_covered bigint,
  polling_units_covered bigint
)
language sql
stable
security definer
set search_path = public
as $$
  select
    s.id as state_id,
    s.name as state_name,
    s.code as state_code,
    s.geopolitical_zone,
    count(p.id) as total_members,
    count(p.id) filter (where p.pvc_status = 'has_pvc') as pvc_holders,
    count(p.id) filter (where p.pvc_status in ('no_pvc_supporter', 'planning_pvc')) as non_pvc_supporters,
    count(p.id) filter (where 'protect_ballots' = any(p.action_teams)) as protect_ballots,
    count(p.id) filter (where 'social_media' = any(p.action_teams)) as social_media,
    count(distinct p.lga_id) as lgas_covered,
    count(distinct p.ward_id) as wards_covered,
    count(distinct p.polling_unit_id) as polling_units_covered
  from public.states s
  left join public.profiles p on p.state_id = s.id
  group by s.id, s.name, s.code, s.geopolitical_zone
  order by total_members desc, s.name asc;
$$;

