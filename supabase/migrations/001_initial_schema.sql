create or replace function public.get_top_mobilizers(p_limit integer default 10)
returns table (
  display_name text,
  state_name text,
  recruits_count bigint
)
language sql
stable
security definer
set search_path = public
as $$
  select
    split_part(ref.full_name, ' ', 1) || ' ' || left(coalesce(nullif(split_part(ref.full_name, ' ', 2), ''), 'M'), 1) || '.' as display_name,
    coalesce(s.name, 'Diaspora') as state_name,
    count(rec.id) as recruits_count
  from public.profiles ref
  join public.profiles rec on rec.referred_by = ref.id
  left join public.states s on s.id = ref.state_id
  group by ref.id, ref.full_name, s.name
  order by recruits_count desc
  limit p_limit;
$$;

