-- Profiles: strict privacy + role-scoped coordinator access
create policy "Users read own profile"
  on public.profiles for select
  using (auth.uid() = id);

create policy "National admins read all profiles"
  on public.profiles for select
  using (public.current_user_role() = 'national_admin');

create policy "State coordinators read assigned state profiles"
  on public.profiles for select
  using (
    public.current_user_role() = 'state_coordinator'
    and state_id = public.current_user_assigned_state()
  );

create policy "Users insert own profile"
  on public.profiles for insert
  with check (auth.uid() = id and role = 'member');

create policy "Users update own profile non-privileged fields"
  on public.profiles for update
  using (auth.uid() = id)
  with check (
    auth.uid() = id
    and role = (select p.role from public.profiles p where p.id = auth.uid())
  );

create policy "National admins manage all profiles"
  on public.profiles for all
  using (public.current_user_role() = 'national_admin');

-- Fundraising campaigns
create policy "Public read active campaigns"
  on public.fundraising_campaigns for select
  using (is_active = true or public.current_user_role() = 'national_admin');

create policy "National admins manage campaigns"
  on public.fundraising_campaigns for all
  using (public.current_user_role() = 'national_admin');

-- Donations
create policy "Members read own donations"
  on public.donations for select
  using (auth.uid() = user_id or public.current_user_role() = 'national_admin');

create policy "Anyone can submit donation pledges"
  on public.donations for insert
  with check (
    status in ('pending', 'pending_verification')
    and (user_id is null or user_id = auth.uid())
  );

create policy "National admins manage donations"
  on public.donations for update
  using (public.current_user_role() = 'national_admin');

-- Gallery & News: public read published, media_editor & national_admin write
