-- Automatic campaign total synchronization when donation becomes verified
create or replace function public.sync_campaign_totals()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if (tg_op = 'INSERT' and new.status = 'verified' and new.campaign_id is not null) then
    update public.fundraising_campaigns
    set raised_amount_ngn = raised_amount_ngn + new.amount_ngn,
        donor_count = donor_count + 1,
        updated_at = now()
    where id = new.campaign_id;
  elsif (tg_op = 'UPDATE' and old.status <> 'verified' and new.status = 'verified' and new.campaign_id is not null) then
    update public.fundraising_campaigns
    set raised_amount_ngn = raised_amount_ngn + new.amount_ngn,
        donor_count = donor_count + 1,
        updated_at = now()
    where id = new.campaign_id;
  elsif (tg_op = 'UPDATE' and old.status = 'verified' and new.status <> 'verified' and old.campaign_id is not null) then
    update public.fundraising_campaigns
    set raised_amount_ngn = greatest(0, raised_amount_ngn - old.amount_ngn),
        donor_count = greatest(0, donor_count - 1),
        updated_at = now()
    where id = old.campaign_id;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_donations_sync_totals on public.donations;
create trigger trg_donations_sync_totals
  after insert or update on public.donations
  for each row execute function public.sync_campaign_totals();

